from .cisa_loader import load_lookups

DATA_DIR = Path(__file__).resolve().parent / "data"
SELECTION_PATH = DATA_DIR / "real_cti_selection.json"
DATASET_PATH = DATA_DIR / "CTI_dataset.json"

ATTACK_ID_IN_TEXT_RE = re.compile(r"(?<![A-Za-z0-9])(?:TA|T)\d{4}(?:\.\d{3})?")


# ══════════════════════════════════════════════════════════════════════════════
# CHAIN ACCESS
# ══════════════════════════════════════════════════════════════════════════════


def load_selection() -> dict[str, dict]:
    data = json.loads(SELECTION_PATH.read_text(encoding="utf-8"))
    return {c["chain_id"]: c for c in data["chains"]}


def step_gold(step: dict) -> list[str]:
    """Gold ATT&CK IDs of a step, whichever loader produced it."""
    return step.get("attack_ids") or [step["attack_id"]]


def step_stix(step: dict) -> list[str]:
    ids = step.get("stix_ids")
    if ids is None:
        ids = [step["stix_id"]] if step.get("stix_id") else []
    return ids


def step_source_text(step: dict) -> str:
    """The English text the Thai narrative is rewritten from."""
    return step.get("cue_en") or step.get("red_team_description", "")


def chain_gold(chain: dict) -> list[str]:
    out: list[str] = []
    for step in chain["steps"]:
        out += step_gold(step)
    return list(dict.fromkeys(out))


def chain_stix(chain: dict) -> list[str]:
    out: list[str] = []
    for step in chain["steps"]:
        out += step_stix(step)
    return list(dict.fromkeys(out))


# ══════════════════════════════════════════════════════════════════════════════
# DATASET FILE
# ══════════════════════════════════════════════════════════════════════════════


def load_dataset() -> dict:
    if not DATASET_PATH.exists():
        return {
            "tier": "real_cti",
            "description": (
                "Thai case-file narratives rewritten by hand from published CTI. "
                "Gold ATT&CK labels are the sources' own (CTID Adversary Emulation "
                "Library; CISA advisories via Zenodo 10.5281/zenodo.14659512) and "
                "are never inferred from this project's graph."
            ),
            "language": "th",
            "samples": [],
        }
    return json.loads(DATASET_PATH.read_text(encoding="utf-8"))


def save_dataset(data: dict) -> None:
    DATASET_PATH.write_text(
        json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8"
    )


def done_chain_ids(data: dict) -> set[str]:
    return {s["chain_id"] for s in data["samples"]}


# ══════════════════════════════════════════════════════════════════════════════
# VALIDATION
# ══════════════════════════════════════════════════════════════════════════════


def validate(sample: dict, chain: dict, names: dict[str, list[str]]) -> list[str]:
    errors: list[str] = []
    narrative = sample.get("query", "")
    narrative_en = sample.get("query_en", "")

    if not narrative:
        return ["empty query"]
    for label, text in (("query", narrative), ("query_en", narrative_en)):
        found = ATTACK_ID_IN_TEXT_RE.findall(text)
        if found:
            errors.append(f"{label} leaks ATT&CK ID(s): {', '.join(found)}")

    steps = sample.get("attack_steps", [])
    if len(steps) != len(chain["steps"]):
        errors.append(
            f"{len(steps)} steps but source chain has {len(chain['steps'])}"
        )
        return errors

    for got, src in zip(steps, chain["steps"]):
        n = got.get("order")
        if n != src["order"]:
            errors.append(f"step {n}: order {n} != source order {src['order']}")
        # Gold labels are never written by hand — `add` copies them from the
        # source chain. A batch may still state them, and then they must agree.
        if "gold_attack_ids" in got and got["gold_attack_ids"] != step_gold(src):
            errors.append(
                f"step {n}: gold {got['gold_attack_ids']} != "
                f"source {step_gold(src)} — labels must not be edited"
            )

        cue = got.get("cue", "")
        if not cue:
            errors.append(f"step {n}: empty cue")
            continue
        if cue not in narrative:
            errors.append(f"step {n}: cue not verbatim in query: {cue[:60]!r}")
        if got.get("cue_type") not in ("named", "described"):
            errors.append(f"step {n}: cue_type must be named or described")
        if got.get("cue_type") == "described":
            for aid in step_gold(src):
                for name in names.get(aid, []):
                    for part in re.split(r":\s*", name):
                        part = part.strip().lower()
                        if len(part) >= 6 and part in cue.lower():
                            errors.append(
                                f"step {n}: described cue spells out the "
                                f"technique name ({part!r})"
                            )
    return errors


# ══════════════════════════════════════════════════════════════════════════════
# COMMANDS
# ══════════════════════════════════════════════════════════════════════════════


def cmd_status(_args) -> None:
    chains, data = load_selection(), load_dataset()
    done = done_chain_ids(data)
    steps = sum(len(s["attack_steps"]) for s in data["samples"])
    print(f"{len(done)}/{len(chains)} chains translated ({steps} steps)")
    by_src: dict[str, int] = {}
    for s in data["samples"]:
        by_src[s["source"]] = by_src.get(s["source"], 0) + 1
    for src, n in sorted(by_src.items()):
        print(f"  {src:38} {n}")

    # Gold is copied into a sample when it is added, so a later loader fix
    # silently leaves already-written samples on stale labels. Catch that.
    drift = []
    for sample in data["samples"]:
        chain = chains.get(sample["chain_id"])
        if chain is None:
            drift.append(f"{sample['id']}: chain {sample['chain_id']} gone")
            continue
        if sample["gold_attack_ids"] != chain_gold(chain):
            drift.append(
                f"{sample['id']} ({sample['chain_id']}): stored gold "
                f"{sample['gold_attack_ids']} != chain {chain_gold(chain)}"
            )
    if drift:
        print(f"\n[DRIFT] {len(drift)} sample(s) hold labels the chain no "
              f"longer has — re-add them:")
        for line in drift:
            print(f"  {line}")


def cmd_brief(args) -> None:
    chains, data = load_selection(), load_dataset()
    done = done_chain_ids(data)
    todo = [c for cid, c in chains.items() if cid not in done]
    for chain in todo[: args.num]:
        print("=" * 100)
        print(f"CHAIN {chain['chain_id']}   [{chain['source_prov']}]")
        for step in chain["steps"]:
            gold = ",".join(step_gold(step))
            name = step.get("technique_name", "")
            hint = f"  cue_type={step['cue_type']}" if "cue_type" in step else ""
            print(f"  --- step {step['order']}  {gold} {name} "
                  f"[{step.get('tactic', '')}]{hint}")
            print("      " + " ".join(step_source_text(step).split())[:600])


def _technique_names(attack_ids: set[str], use_neo4j: bool) -> dict[str, str]:
    """attack_id -> official name, for the reviewer to check cues against.

    Neo4j is the authority here: attack_lookup.json's alias_map covers only a
    subset of parent techniques, so falling back to it alone would leave most
    rows unnamed.
    """
    names: dict[str, str] = {}
    if use_neo4j:
        try:
            from .ctid_loader import STIX_CYPHER
            from ..generate_eval_dataset import Neo4jGroundTruthBuilder

            neo4j = Neo4jGroundTruthBuilder()
            try:
                rows = neo4j.run_query(STIX_CYPHER, {"ids": sorted(attack_ids)})
            finally:
                neo4j.close()
            names = {r["attack_id"]: r["name"] for r in rows if r.get("name")}
        except Exception as e:  # noqa: BLE001 — the sheet is still useful unnamed
            print(f"[REVIEW] Neo4j lookup failed ({e}); names left blank")
    if not names:
        _, aliases = load_lookups()
        names = {aid: (v[0] if v else "") for aid, v in aliases.items()}
    return names


def cmd_review(args) -> None:
    chains, data = load_selection(), load_dataset()
    samples = data["samples"]
    if not samples:
        raise SystemExit("dataset is empty")

    ids = {a for s in samples for a in s["gold_attack_ids"]}
    names = _technique_names(ids, use_neo4j=not args.no_neo4j)

    out = Path(args.out)
    lines = [
        "# Real-CTI Thai Dataset — Review Sheet",
        "",
        f"{len(samples)} สำนวน / "
        f"{sum(len(s['attack_steps']) for s in samples)} steps",
        "",
        "ตรวจ 4 ข้อต่อสำนวน แล้วแก้ใน `data/CTI_dataset.json` โดยตรง:",
        "",
        "1. **สำนวน** — อ่านแล้วเหมือนสำนวนคดีจริงไหม หรือยังกลิ่นแปล",
        "2. **described cue** — อ่าน cue แล้วเดาออกไหมว่าเป็น technique ที่ระบุ "
        "ถ้าเดาไม่ออกเลย = กำกวมเกินไป / ถ้าเดาออกทันทีเพราะมีชื่อเทคนิคอยู่ = "
        "ควรเป็น named",
        "3. **named cue** — ศัพท์อังกฤษที่แทรกดูฝืนไหม",
        "4. **บริบทผู้เสียหาย** — ฉากที่แต่งขึ้นสมเหตุสมผลกับพฤติกรรมไหม",
        "",
        "คอลัมน์ *ต้นฉบับ* คือข้อความอังกฤษจากแหล่งต้นทางที่ cue นั้นแปลมา — "
        "ใช้เทียบว่าแปลตรงและไม่ได้เติมเนื้อหาเอง",
        "",
        "> ⚠️ ถ้าแก้ `cue` ต้องแก้ให้ยังเป็นข้อความย่อย**ตรงตัวอักษร**ใน `query` "
        "ไม่งั้น validator จะไม่ผ่าน ตรวจซ้ำด้วย `thai_dataset status`",
        "",
        "---",
        "",
    ]

    for sample in samples:
        chain = chains.get(sample["chain_id"], {})
        src_steps = {s["order"]: s for s in chain.get("steps", [])}
        url = (sample.get("cti_sources") or [""])[0]

        lines.append(f"## {sample['id']} — {sample['source_prov']}")
        lines.append("")
        if url:
            lines.append(f"ต้นทาง: <{url}>")
            lines.append("")
        lines.append(f"> {sample['query']}")
        lines.append("")
        lines.append(f"*EN:* {sample['query_en']}")
        lines.append("")
        lines.append("| # | cue_type | technique | cue (ไทย) | ต้นฉบับ (EN) |")
        lines.append("|---|----------|-----------|-----------|--------------|")
        for step in sample["attack_steps"]:
            src = src_steps.get(step["order"], {})
            origin = " ".join(step_source_text(src).split())
            if len(origin) > 220:
                origin = origin[:220] + "…"
            tech = ", ".join(
                f"{a} {names.get(a, '?')}".strip() for a in step["gold_attack_ids"]
            )
            cue = step["cue"].replace("|", "\\|")
            origin = origin.replace("|", "\\|")
            lines.append(
                f"| {step['order']} | {step['cue_type']} | {tech} | {cue} | {origin} |"
            )
        lines.append("")
        lines.append("- [ ] ผ่าน / แก้แล้ว")
        lines.append("")

    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"[REVIEW] {len(samples)} samples -> {out}")


def cmd_add(args) -> None:
    chains, data = load_selection(), load_dataset()
    _, names = load_lookups()
    batch = json.loads(Path(args.batch).read_text(encoding="utf-8"))
    if isinstance(batch, dict):
        batch = batch.get("samples", [batch])

    done = done_chain_ids(data)
    accepted, rejected = [], []
    for sample in batch:
        cid = sample.get("chain_id")
        if cid not in chains:
            rejected.append((cid, [f"unknown chain_id {cid!r}"]))
            continue
        if cid in done:
            rejected.append((cid, ["already in dataset"]))
            continue
        errors = validate(sample, chains[cid], names)
        if errors:
            rejected.append((cid, errors))
            continue
        chain = chains[cid]
        attack_steps = [
            {
                "order": src["order"],
                "cue": got["cue"],
                "cue_type": got["cue_type"],
                "gold_attack_ids": step_gold(src),
                "gold_stix_ids": step_stix(src),
            }
            for got, src in zip(sample["attack_steps"], chain["steps"])
        ]
        accepted.append({
            "id": f"rcti_{len(data['samples']) + len(accepted) + 1:03d}",
            "chain_id": cid,
            "query": sample["query"],
            "query_en": sample.get("query_en", ""),
            "relevant_stix_ids": chain_stix(chain),
            "gold_attack_ids": chain_gold(chain),
            "attack_steps": attack_steps,
            "language": "th",
            "category": "incident_analysis",
            "source": chain["source"],
            "source_prov": chain["source_prov"],
            "cti_sources": chain.get("cti_sources", []),
        })

    for cid, errors in rejected:
        print(f"[REJECT] {cid}")
        for e in errors:
            print(f"         - {e}")
    if accepted and not args.dry_run:
        data["samples"] += accepted
        save_dataset(data)
    print(f"\n[ADD] accepted {len(accepted)}, rejected {len(rejected)}"
          f"{' (dry run, nothing written)' if args.dry_run else ''}")
    if accepted and not args.dry_run:
        print(f"[ADD] {len(data['samples'])}/{len(chains)} -> {DATASET_PATH}")
    if rejected:
        sys.exit(1)


def main() -> None:
    parser = argparse.ArgumentParser(description="Thai real-CTI dataset builder")
    sub = parser.add_subparsers(dest="cmd", required=True)

    sub.add_parser("status").set_defaults(func=cmd_status)

    p_brief = sub.add_parser("brief")
    p_brief.add_argument("--num", type=int, default=5)
    p_brief.set_defaults(func=cmd_brief)

    p_review = sub.add_parser("review")
    p_review.add_argument(
        "--out", type=str, default=str(DATA_DIR / "CTI_dataset_review.md")
    )
    p_review.add_argument("--no-neo4j", action="store_true",
                          help="Skip technique-name lookup (names left blank)")
    p_review.set_defaults(func=cmd_review)

    p_add = sub.add_parser("add")
    p_add.add_argument("batch")
    p_add.add_argument("--dry-run", action="store_true")
    p_add.set_defaults(func=cmd_add)

    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
