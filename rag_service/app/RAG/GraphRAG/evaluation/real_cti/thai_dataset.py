"""
Thai case-file dataset builder for the real-CTI tier
=====================================================
The narratives in CTI_dataset.json are written by hand, chain by chain, not
generated by an API call — that is the whole point of this tier. This module
is the scaffolding around that work:

  brief   print the chains still untranslated, in the compact form needed to
          write a Thai narrative from them
  add     validate a batch of hand-written samples and append them
  status  how far the dataset has got
  review  render the dataset as a human review sheet — the mechanical checks
          below cannot tell whether a cue actually reads like the technique it
          is labelled with, and only a person can judge that

`add` refuses a sample that breaks any of the invariants the eval depends on,
so a mistake made while writing 100 narratives fails loudly instead of
quietly weakening the dataset:

  - every step's cue must appear verbatim in the Thai narrative, otherwise
    per-step retrieval scoring has nothing to point at
  - no ATT&CK ID may appear in either narrative — that would hand the answer
    to the retriever
  - a `described` cue must not spell out the technique's English name, which
    is what separates it from a `named` cue
  - gold IDs and step order must match the source chain exactly; the labels
    come from CTID/CISA and translation must not touch them

Usage:
    cd rag_service/app
    python -m RAG.GraphRAG.evaluation.real_cti.thai_dataset status
    python -m RAG.GraphRAG.evaluation.real_cti.thai_dataset brief --num 5
    python -m RAG.GraphRAG.evaluation.real_cti.thai_dataset add batch.json
"""

